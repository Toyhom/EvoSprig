import { test, expect } from '@playwright/test';
import path from 'node:path';

const noOverflow = async (page: import('@playwright/test').Page) => {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
};

test('project search, long names and keyboard navigation work across screen sizes', async ({ page, request }) => {
  const source = await (await request.get('/api/projects/hello')).json();
  const id = `long-workflow-name-for-responsive-navigation-${Date.now().toString(36)}`;
  expect((await request.post('/api/projects', { data: { spec: { ...source.spec, id }, resources: source.resources } })).status()).toBe(201);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const search = page.getByRole('textbox', { name: 'Search projects' });
  await search.fill(id.toUpperCase());
  await expect(page.locator('.project')).toHaveCount(1);
  await search.press('Tab');
  await expect(page.locator('.project')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('h1')).toHaveText(id);
  await expect(page.locator('.project')).toHaveAttribute('aria-current', 'page');
  await search.fill('no-such-project');
  await expect(page.getByText('没有匹配的项目')).toBeVisible();
  await search.fill('');
  await noOverflow(page);
  await page.setViewportSize({ width: 1024, height: 768 });
  await noOverflow(page);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(search).not.toBeVisible();
  const menu = page.getByRole('button', { name: '打开项目导航' });
  await menu.click();
  await expect(search).toBeVisible();
  const close = page.locator('.mobile-close');
  await expect(close).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button', { name: '中文 / EN' })).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(close).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(menu).toBeFocused();
  await expect(search).not.toBeVisible();
  await menu.click();
  await search.fill('hello');
  await page.locator('.project[title="hello"]').click();
  await expect(page.locator('h1')).toHaveText('hello');
  await expect(search).not.toBeVisible();
  await expect(menu).toBeFocused();
  await noOverflow(page);
  await menu.click();
  await search.fill(id);
  const evidence = process.env.EVOSPRIG_EVIDENCE_DIR;
  if (evidence) await page.screenshot({ path: path.join(evidence, 'studio-mobile-navigation.png') });
  await page.locator('.project').click();
  await page.getByRole('button', { name: '记忆与资料', exact: true }).click();
  await noOverflow(page);
  await page.setViewportSize({ width: 320, height: 740 });
  await noOverflow(page);
  await page.getByRole('button', { name: '改进', exact: true }).click();
  await noOverflow(page);
  await page.getByRole('button', { name: '画布', exact: true }).click();
  await noOverflow(page);
  await menu.click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await expect(page.locator('main')).not.toHaveAttribute('inert');
  await noOverflow(page);
  expect(errors).toEqual([]);
});
